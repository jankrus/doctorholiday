#!/usr/bin/env bash
# Prepares the manifests for images from the registry (issue #43): a Kustomize overlay in
# .cache/k8s-registry/ that takes infrastructure/k8s and replaces the images of the application by
# the digests in reports/images/<component>/image-ref.txt (written by the build job, signed and
# verified before). The committed manifests are not changed.
#
#   scripts/k8s-registry-overlay.sh
#
# Environment
#   PULL_SECRET   name of an image pull secret (see k8s-pull-secret.sh); the overlay then adds it to
#                 the backend and frontend Deployments. Without it the images must be public.
#   REPORTS_DIR   default `reports`
set -euo pipefail

cd "$(git rev-parse --show-toplevel)"
reports="${REPORTS_DIR:-reports}"
out=".cache/k8s-registry"
mkdir -p "$out"

images=""
for component in backend frontend; do
  ref_file="$reports/images/$component/image-ref.txt"
  [[ -s "$ref_file" ]] || { echo "missing $ref_file" >&2; exit 1; }
  ref="$(tr -d '[:space:]' < "$ref_file")"
  expected="ghcr.io/jankrus/doctorholiday-$component"
  # By digest only, and only the image of this project: nothing else may end up in the cluster.
  if [[ ! "$ref" =~ ^${expected}@(sha256:[0-9a-f]{64})$ ]]; then
    echo "unexpected image reference for $component: $ref" >&2
    exit 1
  fi
  images+="  - name: $expected
    newName: $expected
    digest: ${BASH_REMATCH[1]}
"
done

patches=""
if [[ -n "${PULL_SECRET:-}" ]]; then
  for component in backend frontend; do
    patches+="  - target:
      kind: Deployment
      name: $component
    patch: |-
      - op: add
        path: /spec/template/spec/imagePullSecrets
        value:
          - name: $PULL_SECRET
"
  done
  patches="patches:
$patches"
fi

cat > "$out/kustomization.yaml" << YAML
# Generated by scripts/k8s-registry-overlay.sh (#43); not committed.
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - ../../infrastructure/k8s
images:
${images}${patches}
YAML
echo "wrote $out/kustomization.yaml"
grep -E 'digest:' "$out/kustomization.yaml"
